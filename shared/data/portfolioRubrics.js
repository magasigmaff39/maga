export const FIELD_LIST = Object.values(FIELD_RUBRICS).map((f) => ({ id: f.id, title: f.title }));

export function fieldForMajors(majors = []) {
  const counts = new Map();
  for (const m of majors) {
    const f = MAJOR_TO_FIELD[m];
    if (f) counts.set(f, (counts.get(f) || 0) + 1);
  }
  let best = 'tech';
  let bestN = 0;
  for (const [f, n] of counts) {
    if (n > bestN) {
      best = f;
      bestN = n;
    }
  }
  return best;
}
