export const DICTIONARIES: Record<AppLanguage, Dict> = { kk, en, ru };

export function translate(lang: AppLanguage, key: string, vars?: Record<string, string | number>): string {
  const raw = DICTIONARIES[lang]?.[key] ?? DICTIONARIES.ru[key] ?? key;
  if (!vars) return raw;
  return raw.replace(/\{(\w+)\}/g, (_, k) => (vars[k] !== undefined ? String(vars[k]) : `{${k}}`));
}
